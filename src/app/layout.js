import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata = {
  title: "Planner Flow",
  description: "Planner Flow: a personal planner and journal. Server and admin panel.",
};

// suppressHydrationWarning on <html> and <body> only: browser extensions
// (Grammarly, dark-mode and password-manager add-ons…) add attributes to these
// two tags before React loads. It doesn't hide mismatches inside the page.
export default function RootLayout({ children }) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
      suppressHydrationWarning
    >
      <body className="min-h-full flex flex-col" suppressHydrationWarning>
        {children}
      </body>
    </html>
  );
}
